-- deleted: the newest event is a deletion the row does not reflect
DELETE
FROM ##symbols_table## s
    USING (SELECT DISTINCT ON (sender_id, symbol_id) sender_id, symbol_id, id, event_type
           FROM ##symbol_events_table##
           WHERE event_type IN (0, 1)
           ORDER BY sender_id, symbol_id, id DESC) l
WHERE l.sender_id = s.sender_id
  AND l.symbol_id = s.symbol_id
  AND l.event_type = 1
  AND l.id > s.source_event_row_id;

-- swept: a finished resync skipped the row while the trigger was absent, and a sweep leaves no event
DELETE
FROM ##symbols_table## s
    USING (SELECT started.sender_id, max(started.id) AS watermark
           FROM ##symbol_events_table## started
           WHERE started.event_type = 2
             AND started.id < (SELECT max(finished.id)
                               FROM ##symbol_events_table## finished
                               WHERE finished.sender_id = started.sender_id
                                 AND finished.event_type = 3)
           GROUP BY started.sender_id) w
WHERE w.sender_id = s.sender_id
  AND s.source_event_row_id < w.watermark;
